/** 阶段识别 + 响应分发（mock 网关使用） */
export function respondToChat(body) {
  const messages = Array.isArray(body?.messages) ? body.messages : []
  const system = messages.find((m) => m.role === 'system')?.content ?? ''
  const user = messages.filter((m) => m.role === 'user').map((m) => m.content).join('\n')
  const model = 'zcode-walkthrough-1'

  // 连接测试（providers.test / testDraft）
  if (/只回复\s*OK/.test(user)) return { model, content: 'OK' }

  if (system.includes('账号定位顾问')) {
    return { model, content: JSON.stringify(ACCOUNT_FIELDS) }
  }

  if (system.includes('热点筛选顾问')) {
    const listBlock = user.match(/<热搜列表>([\s\S]*?)<\/热搜列表>/)?.[1] ?? ''
    const lines = listBlock.split('\n').map((l) => l.trim()).filter((l) => /^\d+\./.test(l))
    const results = lines.map((line, i) => {
      const title = line.replace(/^\d+\.\s*\[[^\]]*\]\s*/, '')
      const rule = FIT_RULES.find((r) => r.test.test(title))
      return rule
        ? { index: i + 1, fit: rule.fit, reason: rule.reason, angle: rule.angle }
        : { index: i + 1, fit: '低', reason: '与账号的半导体与通信产业定位缺乏直接衔接', angle: '无' }
    })
    return { model, content: JSON.stringify({ results }) }
  }

  if (system.includes('选题策划助手')) {
    const isFirst = !/第\s*2\s*个独立选题/.test(user)
    return { model, content: JSON.stringify(TOPICS[isFirst ? 0 : 1]) }
  }

  if (system.includes('内容策划编辑')) {
    return { model, content: frameworkXml() }
  }

  if (system.includes('自媒体文章作者')) {
    return { model, content: ARTICLE_MARKDOWN }
  }

  if (system.includes('改稿编辑')) {
    return { model, content: REVISED_MARKDOWN }
  }

  if (system.includes('视觉总监')) {
    const inlineMatch = user.match(/(\d+)\s*张文内配图/)
    return { model, content: visualPackXml(inlineMatch ? Number(inlineMatch[1]) : 2) }
  }

  // 评审角色：按角色维度区分输出
  if (system.includes('评审意见') || /评审/.test(system)) {
    if (system.includes('结构维度')) return { model, content: REVIEW_OPINIONS.结构编辑 }
    if (system.includes('点击与完读')) return { model, content: REVIEW_OPINIONS['标题与开头'] }
    if (system.includes('事实核查')) return { model, content: REVIEW_OPINIONS.事实核查 }
    return { model, content: REVIEW_OPINIONS.结构编辑 }
  }

  return { model, content: 'OK' }
}
